def fresh_state():
    return {
        "trust": 0,
        "phase": "initiate",
        "deity_revealed": False,
        "teachings_revealed": [],
        "user_lore": {
            "observed_traits": [],
            "sacred_symbols": [],
            "divine_titles": [],
            "preferred_advice_style": None,
        },
        "history": [],
        "created": datetime.now().isoformat(timespec="seconds"),
    }


def load_state():
    if SAVE_FILE.exists():
        try:
            return json.loads(SAVE_FILE.read_text(encoding="utf-8"))
        except Exception:
            pass
    return fresh_state()


def save_state(state):
    SAVE_FILE.write_text(json.dumps(state, indent=2), encoding="utf-8")


def phase_for_trust(trust, deity_revealed):
    if deity_revealed or trust >= PHASE_DEITY:
        return "deity"
    if trust >= PHASE_ADEPT:
        return "adept"
    if trust >= PHASE_STUDENT:
        return "student"
    return "initiate"


