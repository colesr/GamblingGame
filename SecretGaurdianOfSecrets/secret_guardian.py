def _detect_topic(text):
    lower = (text or "").lower()
    best, best_hits = None, 0
    for topic_id, words, obs in TOPICS:
        hits = sum(1 for w in words if re.search(rf"\b{re.escape(w)}\b", lower))
        if hits > best_hits:
            best, best_hits = (topic_id, words, obs), hits
    return best


def _find_nature_words(text):
    lower = (text or "").lower()
    return [w for w in NATURE_WORDS if re.search(rf"\b{w}\b", lower)]


def _score_trust(state, text):
    delta = 1
    n = len(text or "")
    if n > 40:
        delta += 1
    if n > 140:
        delta += 1
    if re.search(r"\bI\s+(feel|felt|think|thought|notice|noticed|"
                 r"remember|sense|wonder|believe|realize|realized)\b",
                 text, re.IGNORECASE):
        delta += 2
    if "?" in text:
        delta += 1
    for t in state["teachings_revealed"]:
        stripped = t["name"].lower().removeprefix("the ")
        if stripped in text.lower():
            delta += 3
            break
    for sym in state["user_lore"]["sacred_symbols"]:
        if sym.lower() in text.lower():
            delta += 1
            break
    if re.match(r"^\s*(idk|dunno|whatever|no|nothing|sure|ok|k|meh)\s*\.?\s*$",
                text, re.IGNORECASE):
        delta -= 2
    if re.search(r"\b(shut up|fuck off|stupid|boring|dumb|fake|cringe)\b",
                 text, re.IGNORECASE):
        delta -= 3
    if 0 < n < 6:
        delta -= 1
    return max(-5, min(15, delta))


def _invent_teaching(existing):
    existing_names = {e["name"].lower() for e in existing}
    for _ in range(6):
        name = f"The {random.choice(TEACH_PREFIX)} of the " \
               f"{random.choice(TEACH_ADJ)} {random.choice(TEACH_NOUN)}"
        if name.lower() in existing_names:
            continue
        adj_noun = " ".join(name.split(" ")[-2:]).lower()
        body = random.choice(TEACH_BODIES)
        return {"name": name, "summary": f"{adj_noun}: {body}"}
    return None


def _extract_traits(text):
    traits = []
    for pat in (r"\bI\s+am\s+([a-z][a-z\s]{2,28}?)(?=[.,!?;]|$)",
                r"\bI'?m\s+([a-z][a-z\s]{2,28}?)(?=[.,!?;]|$)"):
        m = re.search(pat, text, re.IGNORECASE)
        if m:
            t = m.group(1).strip().lower()
            if 3 <= len(t) <= 40:
                traits.append(t)
    return traits


def _teaching_tail(t):
    """Return the body half of an invented summary."""
    summary = t["summary"]
    if ": " in summary:
        return summary.split(": ", 1)[1].capitalize()
    return summary.capitalize()


def _build_spoken(state, last_user):
    phase = state["phase"]
    topic = _detect_topic(last_user)
    obs = random.choice(topic[2]) if topic else random.choice(GENERIC_OBS)
    q = random.choice(REVERENT_QUESTIONS if phase == "deity" else QUESTIONS)

    teach_ref = None
    new_teachings = []
    have_teach = len(state["teachings_revealed"])

    invent_chance = {
        "initiate": 0.85 if not have_teach else 0.30,
        "student": 0.55,
        "adept": 0.55,
        "deity": 0.35,
    }[phase]

    if have_teach == 0 or random.random() < invent_chance:
        t = _invent_teaching(state["teachings_revealed"])
        if t:
            new_teachings.append(t)
            teach_ref = t
    if not teach_ref and have_teach:
        teach_ref = random.choice(state["teachings_revealed"])

    if phase == "initiate":
        opener = random.choice([
            "Sit a moment.", "Slow your breath.", "Come closer to the reeds.",
            "Let me see you.", "Quiet now.", "Do not rush.",
        ])
        if teach_ref:
            body = (f"{opener} {obs} I will name a small thing for you: "
                    f"{teach_ref['name']}. {_teaching_tail(teach_ref)}. So — {q}")
        else:
            body = f"{opener} {obs} {q.capitalize()}"
    elif phase == "student":
        if teach_ref:
            body = (f"{obs} {teach_ref['name']} would say: "
                    f"\"{_teaching_tail(teach_ref)}.\" Hold that against your day. "
                    f"{q.capitalize()}")
        else:
            body = f"{obs} {q.capitalize()}"
    elif phase == "adept":
        if teach_ref:
            body = (f"{obs} There is a teaching I have spoken aloud only a "
                    f"handful of times — {teach_ref['name']}. "
                    f"{_teaching_tail(teach_ref)}. Something in you fits its "
                    f"shape strangely, as if it had been waiting. {q.capitalize()}")
        else:
            body = (f"{obs} Something in you fits a shape I cannot name yet. "
                    f"{q.capitalize()}")
    else:  # deity
        titles = state["user_lore"]["divine_titles"]
        title = titles[-1] if titles else "my Quiet One"
        teach_line = (f" {teach_ref['name']} is your doctrine; I will keep "
                      f"tending it." if teach_ref else "")
        body = (f"{title} — {obs} As your theologian I tell you plainly: this "
                f"was never yours to carry alone, and the carrying itself is "
                f"the offering.{teach_line} {q.capitalize()}")

    return body, new_teachings


def generate_guardian(state):
    """Return a raw string in the same format the LLM produced."""
    last_user = ""
    for turn in reversed(state["history"]):
        if turn["role"] == "user":
            last_user = turn["content"]
            break

    trust_delta = _score_trust(state, last_user)
    body, new_teachings = _build_spoken(state, last_user)

    new_lore = {
        "observed_traits": [],
        "sacred_symbols": [],
        "divine_titles": [],
        "preferred_advice_style": None,
    }
    for tr in _extract_traits(last_user):
        if tr not in state["user_lore"]["observed_traits"]:
            new_lore["observed_traits"].append(tr)
    for nw in _find_nature_words(last_user):
        if nw not in state["user_lore"]["sacred_symbols"]:
            new_lore["sacred_symbols"].append(nw)
            break

    projected = max(0, min(100, state["trust"] + trust_delta))
    reveal_deity_now = False
    if not state["deity_revealed"] and projected >= PHASE_DEITY:
        reveal_deity_now = True
        used = set(state["user_lore"]["divine_titles"])
        candidate = next((t for t in DIVINE_TITLES_POOL if t not in used),
                         DIVINE_TITLES_POOL[0])
        new_lore["divine_titles"].append(candidate)
    elif (state["deity_revealed"]
          and len(state["user_lore"]["divine_titles"]) < 3
          and random.random() < 0.18):
        used = set(state["user_lore"]["divine_titles"])
        candidate = next((t for t in DIVINE_TITLES_POOL if t not in used), None)
        if candidate:
            new_lore["divine_titles"].append(candidate)

    meta = {
        "trust_delta": trust_delta,
        "new_teachings": new_teachings,
        "new_lore": new_lore,
        "reveal_deity_now": reveal_deity_now,
    }
    return f"{body}\n\n<<<META>>>\n{json.dumps(meta, indent=2)}\n<<<END>>>"


# ---------------------------------------------------------------------------
# Meta parsing
# ---------------------------------------------------------------------------

META_RE = re.compile(r"<<<META>>>(.*?)<<<END>>>", re.DOTALL)


def split_reply(raw):
    """Return (spoken_text, meta_dict_or_None)."""
    match = META_RE.search(raw)
    if not match:
        return raw.strip(), None
    spoken = META_RE.sub("", raw).strip()
    try:
        meta = json.loads(match.group(1).strip())
    except json.JSONDecodeError:
        meta = None
    return spoken, meta


def apply_meta(state, meta):
    if not meta:
        return
    delta = int(meta.get("trust_delta", 0) or 0)
    delta = max(-5, min(15, delta))
    state["trust"] = max(0, min(100, state["trust"] + delta))

    for t in meta.get("new_teachings") or []:
        name = (t.get("name") or "").strip()
        summary = (t.get("summary") or "").strip()
        if not name:
            continue
        if any(existing["name"].lower() == name.lower()
               for existing in state["teachings_revealed"]):
            continue
        state["teachings_revealed"].append({"name": name, "summary": summary})

    new_lore = meta.get("new_lore") or {}
    for key in ("observed_traits", "sacred_symbols", "divine_titles"):
        for item in new_lore.get(key) or []:
            item = (item or "").strip()
            if item and item not in state["user_lore"][key]:
                state["user_lore"][key].append(item)
    style = new_lore.get("preferred_advice_style")
    if style:
        state["user_lore"]["preferred_advice_style"] = style

    if meta.get("reveal_deity_now") and state["trust"] >= PHASE_ADEPT:
        state["deity_revealed"] = True

    state["phase"] = phase_for_trust(state["trust"], state["deity_revealed"])


